"""Render existing frozen summaries; no scoring, sampling, bootstrap or selection."""
import hashlib,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def paths():
    result=[('density','2026-08','STUDIES/fresh_real_value_v1/execution-20261027/production-metadata/campaign01--campaign--summary.json')]
    for m in ('2026-04','2026-05','2026-06'):
        result.append(('density',m,f'STUDIES/market_replication_v1/execution-20261027/{m}/summary.json'))
        result.append(('decision',m,f'STUDIES/bounded_inventory_decision_v1/evidence/{m}-summary.json'))
        result.append(('tail',m,f'STUDIES/predictive_risk_limits_v1/evidence-20261027/campaign01/batch/reports/{m}/summary.json'))
    for m in ('2025-12','2026-01','2026-02'):
        result.append(('tail',m,f'STUDIES/fresh_risk_confirmation_v1/evidence/{m}-summary.json'))
    return result
def records():
    pinned=json.loads((ROOT/'paper/TABLE-SOURCES.json').read_bytes())
    rows=[]
    for kind,month,name in paths():
        p=ROOT/name
        if sha(p)!=pinned[name]:raise ValueError('Table source changed: '+name)
        s=json.loads(p.read_bytes());n=s['planned_origins']
        if kind=='density':
            for arm in ('rolling_t5','ewma_t5'):
                v=s['paired']['candidate_minus_'+arm]
                if v['available_origins']!=n:raise ValueError('Incomplete density panel')
                rows.append(dict(kind=kind,month=month,control=arm,endpoint='logscore',n=n,mean=v['available_mean'],interval=v['block_intervals']['48'],source=name))
        elif kind=='tail':
            for arm in ('rolling_t5','ewma_t5'):
                for side in ('long','short'):
                    v=s['comparisons'][arm+'_'+side]
                    if v['available']!=n or v['planned']!=n:raise ValueError('Incomplete tail panel')
                    rows.append(dict(kind=kind,month=month,control=arm,endpoint=side,n=n,mean=v['mean_advantage'],interval=v['loss_block_intervals']['48'],source=name))
        else:
            for arm in ('ewma_t5','rolling_t5','always_retain','always_convert'):
                v=s['comparisons']['decision_'+arm]
                if v['available']!=n or v['planned']!=n:raise ValueError('Incomplete decision panel')
                rows.append(dict(kind=kind,month=month,control=arm,endpoint='bounded_cost',n=n,mean=v['mean_advantage'],interval=v['block_intervals']['48'],source=name))
    return rows
def render(rows):
    lines=['# Completed-study numerical results','',
           'Generated by build_tables.py from hash-pinned summaries. No scores or intervals are recomputed.',
           'All intervals shown are the original descriptive 95% intervals using 48-origin blocks.',
           'They are not simultaneous confidence bands or guarantees against longer temporal dependence.','']
    labels={'density':'Predictive density: SV minus control, nats per origin',
            'tail':'Tail pinball loss: control minus SV, millionths of log-return loss',
            'decision':'Bounded decision cost: control minus SV, millionths of endowed notional'}
    for kind,label in labels.items():
        lines += ['## '+label,'','| Month | Control | Endpoint | Origins | Mean advantage | Original interval |','|---|---|---|---:|---:|---|']
        factor=1 if kind=='density' else 1e6
        for r in sorted((r for r in rows if r['kind']==kind),key=lambda r:(r['month'],r['control'],r['endpoint'])):
            lo,hi=r['interval'];lines.append(f"| {r['month']} | {r['control']} | {r['endpoint']} | {r['n']} | {r['mean']*factor:.6f} | [{lo*factor:.6f}, {hi*factor:.6f}] |")
        lines.append('')
    lines += ['The density comparisons are E62/E64 historical panels. Tail comparisons for April–June are E65 retrospective reuse; December–February are E66 historical/project-access holdouts, with two original reference failures. The decision table is E67 exploratory reuse of exposed E64 data and is not a self-financing investment return. No pooled significance or profitability conclusion is implied.','']
    return '\n'.join(lines)
if __name__=='__main__':
    rows=records()
    (ROOT/'paper/RESULTS-TABLES.md').write_text(render(rows),encoding='utf-8')
    (ROOT/'paper/table-data.json').write_text(json.dumps(rows,indent=2,allow_nan=False)+'\n')
    print('Rendered',len(rows),'complete fixed comparisons')
