#!/usr/bin/env python3
"""WP83 tables, predictions and the frozen rule. Writes artifacts/results-table.md and summary.json."""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ART = HERE / "artifacts"
P = json.loads((HERE / "protocol.json").read_text(encoding="utf-8"))
SEEDS, MODELS = P["seeds"], P["models"]


def load(sub):
    out = {}
    for p in sorted((ART / sub).glob("*.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        out[p.stem] = r
    return out


def key(m, a, t, s):
    return f"{m}-{a}-t{t}-{s}"


def main():
    cells, robust = load("cells"), load("robust")
    md = ["# pymc_gil_free_default_v1 (WP83) results (generated by analyze.py)", "",
          "Walls pinned, co-tenanted. Hashes, gates and fault counts do not depend on load.", ""]
    rows, per = [], {}
    for m in MODELS:
        g = lambda a, t, s: cells.get(key(m, a, t, s), {})  # noqa: E731
        ok = lambda r: r.get("status") == "ok"  # noqa: E731
        st = {f"{a}t{t}": [g(a, t, s).get("status", "missing") for s in SEEDS]
              for a, t in [("default", 1), ("numba", 1), ("gilfree", 1), ("gilfree", 4)]}
        err = sorted({g(a, t, s).get("error", g(a, t, s).get("stderr", ""))[:160]
                      for a, t in [("gilfree", 1), ("gilfree", 4), ("default", 1), ("numba", 1)] for s in SEEDS
                      if not ok(g(a, t, s))})
        def ident(a, ta, b, tb):
            v = [g(a, ta, s)["samples_sha256"] == g(b, tb, s)["samples_sha256"]
                 for s in SEEDS if ok(g(a, ta, s)) and ok(g(b, tb, s))]
            return [sum(v), len(v)]
        def passed(a, t):
            return sum(1 for s in SEEDS if ok(g(a, t, s)) and g(a, t, s)["passed"])
        wr = [g("gilfree", 1, s)["wall_per_call_us"] / g("default", 1, s)["wall_per_call_us"]
              for s in SEEDS if ok(g("gilfree", 1, s)) and ok(g("default", 1, s))]
        wr4 = [g("gilfree", 4, s)["wall_seconds"] / g("default", 1, s)["wall_seconds"]
               for s in SEEDS if ok(g("gilfree", 4, s)) and ok(g("default", 1, s))]
        zs = []
        for s in SEEDS:
            a, b = g("gilfree", 1, s), g("default", 1, s)
            if ok(a) and ok(b):
                z = max(abs(x - y) / math.sqrt(u * u + v * v) for x, y, u, v in
                        zip(a["mean"], b["mean"], a["mcse_mean"], b["mcse_mean"]) if u > 0 or v > 0)
                zs.append(z)
        def_ok = all(ok(g("default", 1, s)) for s in SEEDS)
        gf_ok = all(ok(g("gilfree", t, s)) for t in (1, 4) for s in SEEDS)
        construct_errors = [g("gilfree", t, s).get("error", "") for t in (1, 4) for s in SEEDS
                            if g("gilfree", t, s).get("status") == "construct_error"]
        known = m == "initvals_data"
        fails_closed = bool(construct_errors) and all(e.startswith("NotImplementedError") for e in construct_errors) \
            and all(g("gilfree", t, s).get("status") == "construct_error" for t in (1, 4) for s in SEEDS)
        idn = ident("gilfree", 1, "numba", 1)
        differs = []
        if idn[1] and idn[0] < idn[1]:
            differs.append("not identical to numba control")
        if gf_ok and passed("gilfree", 1) < passed("default", 1):
            differs.append("fewer gate passes")
        if sum(1 for z in zs if z > 5) >= 2:
            differs.append("means |z| > 5 on >= 2 seeds")
        per[m] = {"status": st, "errors": err, "id_gilfree_numba": idn, "id_gilfree_t1_t4": ident("gilfree", 1, "gilfree", 4),
                  "id_gilfree_default": ident("gilfree", 1, "default", 1), "id_numba_default": ident("numba", 1, "default", 1),
                  "passed": {f"{a}_t{t}": passed(a, t) for a, t in [("default", 1), ("numba", 1), ("gilfree", 1), ("gilfree", 4)]},
                  "wall_ratio_t1_median": float(np.median(wr)) if wr else None,
                  "wall_ratio_gilfree_t4_vs_default_t1_median": float(np.median(wr4)) if wr4 else None,
                  "max_z_per_seed": zs, "default_ok": def_ok, "gilfree_ok": gf_ok, "known_limitation": known,
                  "fails_closed": fails_closed, "differs": differs,
                  "callable_target": {a: g(a, 1, SEEDS[0]).get("target_callable") for a in ("default", "gilfree")}}
        rows.append(m)
    md += ["## Breadth (3 seeds; identical = identical/compared; gates = passing cells)", "",
           "| model | gil_free ≡ numba | gil_free t1 ≡ t4 | gil_free ≡ default | gates default / numba / gf t1 / gf t4 | "
           "wall/grad gf ÷ default (t1) | wall gf t4 ÷ default t1 | max \\|z\\| per seed | errors |",
           "|---|---|---|---|---|---:|---:|---|---|"]
    for m in rows:
        r = per[m]
        pz = ", ".join(f"{z:.1f}" for z in r["max_z_per_seed"]) or "—"
        f = lambda x: f"{x:.2f}" if x is not None else "—"  # noqa: E731
        md.append(f"| {m} | {r['id_gilfree_numba'][0]}/{r['id_gilfree_numba'][1]} | {r['id_gilfree_t1_t4'][0]}/{r['id_gilfree_t1_t4'][1]} | "
                  f"{r['id_gilfree_default'][0]}/{r['id_gilfree_default'][1]} | "
                  f"{'/'.join(str(v) for v in r['passed'].values())} | {f(r['wall_ratio_t1_median'])} | "
                  f"{f(r['wall_ratio_gilfree_t4_vs_default_t1_median'])} | {pz} | {'; '.join(r['errors']) or '—'} |")
    md.append("")
    # robustness
    rb = {}
    for m in P["robustness"]["models"]:
        rs = [robust.get(f"{m}-{i:03d}", {"status": "missing"}) for i in range(1, P["robustness"]["reps"] + 1)]
        faults = sum(1 for r in rs if r.get("status") != "ok")
        hashes = [r.get("samples_sha256") for r in rs if r.get("status") == "ok"]
        ref = hashes[0] if hashes else None
        rb[m] = {"runs": len(rs), "faults": faults, "non_identical": sum(1 for h in hashes if h != ref),
                 "statuses": sorted({r.get("status") for r in rs}),
                 "matches_breadth_seed_hash": None}
    md += ["## Robustness (gil_free, threads=4, seed 8383500, 50 child processes per model)", "",
           "| model | runs | faults | non-identical |", "|---|---:|---:|---:|"]
    md += [f"| {m} | {v['runs']} | {v['faults']} | {v['non_identical']} |" for m, v in rb.items()] + [""]
    # predictions
    runnable = [m for m in MODELS if per[m]["gilfree_ok"]]
    pred = {
        "P1": all(per[m]["id_gilfree_numba"][0] == per[m]["id_gilfree_numba"][1] for m in MODELS if per[m]["id_gilfree_numba"][1]),
        "P2": all(per[m]["id_gilfree_t1_t4"][0] == per[m]["id_gilfree_t1_t4"][1] for m in MODELS if per[m]["id_gilfree_t1_t4"][1]),
        "P3": sum(1 for m in runnable if per[m]["id_gilfree_default"][1] and per[m]["id_gilfree_default"][0] == per[m]["id_gilfree_default"][1]) <= 3,
        "P4": all(per[m]["wall_ratio_t1_median"] is not None and 0.1 <= per[m]["wall_ratio_t1_median"] <= 0.9 for m in runnable),
        "P5": all(z <= 5 for m in runnable for z in per[m]["max_z_per_seed"]),
        "P6": all(per[m]["passed"]["gilfree_t1"] >= per[m]["passed"]["default_t1"] for m in runnable),
        "P7": [m for m in MODELS if not (per[m]["gilfree_ok"] and per[m]["default_ok"])] == ["initvals_data"]
              and per["initvals_data"]["fails_closed"] and per["initvals_data"]["default_ok"],
        "P8": all(v["faults"] == 0 and v["non_identical"] == 0 for v in rb.values()),
    }
    md += ["## Predictions", ""] + [f"- {k}: {'held' if v else 'FAILED'}" for k, v in pred.items()] + [""]
    r1_bad = [m for m in MODELS if per[m]["default_ok"] and not per[m]["gilfree_ok"]
              and not (per[m]["known_limitation"] and per[m]["fails_closed"])]
    r2_bad = [m for m in MODELS if per[m]["default_ok"] and per[m]["differs"]]
    r3 = all(v["faults"] == 0 and v["non_identical"] == 0 for v in rb.values())
    rule = {"R1_models_failing": r1_bad, "R2_models_differing": r2_bad, "R3_robust": r3,
            "known_limitation_fails_closed": per["initvals_data"]["fails_closed"],
            "propose_default": not r1_bad and not r2_bad and r3}
    md += ["## Decision rule (frozen)", "", "```json", json.dumps(rule, indent=1), "```", ""]
    (ART / "summary.json").write_text(json.dumps({"per_model": per, "robustness": rb, "predictions": pred,
                                                  "rule": rule}, indent=1, default=float), encoding="utf-8")
    (ART / "results-table.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
