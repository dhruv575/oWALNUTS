#!/usr/bin/env python3
"""Tables, predictions and the frozen decision rule for python_callpath_linux_v1 (WP78).

    python analyze.py      # reads artifacts/{micro,cells}, writes artifacts/results-table.md and summary.json

Pure post-processing of the cell records; no sampling.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ART = HERE / "artifacts"
P = json.loads((HERE / "protocol.json").read_text(encoding="utf-8"))
SEEDS, TARGETS, THREADS = P["seeds"], P["targets"], P["threads"]
OW = P["owalnuts_arms"]
ARMS = OW + P["nutpie_arms"]
PRED = P["predictions"]


def gm(xs):
    xs = [x for x in xs if x is not None and x > 0 and math.isfinite(x)]
    return float(math.exp(sum(math.log(x) for x in xs) / len(xs))) if xs else None


def med(xs):
    xs = [x for x in xs if x is not None]
    return float(np.median(xs)) if xs else None


def load():
    cells, micro = {}, {}
    for p in sorted((ART / "cells").glob("*.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        if "step" in r:  # process_error record
            _, target, arm, t, seed = r["step"]
            r.update(target=target, arm=arm, threads=int(t), seed=int(seed))
        cells[(r["target"], r["arm"], int(r["threads"]), int(r["seed"]))] = r
    for p in sorted((ART / "micro").glob("*.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        micro[(r["target"], r["path"])] = r
    return cells, micro


def ok(c, key):
    r = c.get(key)
    return r if r is not None and r.get("status") == "ok" else None


def fmt(x, nd=2):
    if x is None:
        return "—"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, str):
        return x
    if abs(x) >= 1000:
        return f"{x:,.0f}"
    if abs(x) >= 100:
        return f"{x:.0f}"
    return f"{x:.{nd}f}"


def inr(x, lo_hi):
    return x is not None and lo_hi[0] <= x <= lo_hi[1]


def main() -> None:
    cells, micro = load()
    out: dict = {"cells_total": len(cells), "cells_ok": sum(1 for r in cells.values() if r.get("status") == "ok"),
                 "micro_total": len(micro), "micro_ok": sum(1 for r in micro.values() if r.get("status") == "ok")}
    md = ["# python_callpath_linux_v1 (WP78) results (generated by analyze.py)", "",
          "Walls are **pinned, co-tenanted** (lane 4 = cores 12-15 of a shared 16-core box, three other lanes "
          "active). ESS per gradient, gate counts and draw hashes do not depend on the machine load.", ""]
    md.append(f"Cells: {out['cells_ok']}/{out['cells_total']} sampler cells ok, "
              f"{out['micro_ok']}/{out['micro_total']} micro cells ok.")
    md.append("")
    failures = [dict(target=k[0], arm=k[1], threads=k[2], seed=k[3], status=r.get("status"),
                     error=str(r.get("error", ""))[:300]) for k, r in sorted(cells.items()) if r.get("status") != "ok"]
    failures += [dict(target=k[0], path=k[1], status=r.get("status"), error=str(r.get("error", ""))[:300])
                 for k, r in sorted(micro.items()) if r.get("status") != "ok"]
    out["failures"] = failures
    if failures:
        md += ["## Failed cells (results, not rerun)", ""] + [f"- `{json.dumps(f)}`" for f in failures] + [""]

    # ---- per (target, arm, threads) aggregates
    agg = {}
    for t in TARGETS:
        for a in ARMS:
            for th in THREADS:
                rs = [ok(cells, (t, a, th, s)) for s in SEEDS]
                good = [r for r in rs if r]
                agg[(t, a, th)] = {
                    "ok": len(good), "n": len(SEEDS),
                    "wall_per_call_us": med([r["wall_per_call_us"] for r in good]),
                    "wall_per_call_us_seeds": [r["wall_per_call_us"] if r else None for r in rs],
                    "ess_per_second": gm([r["ess_per_second"] for r in good]),
                    "ess_per_gradient": gm([r["ess_per_gradient"] for r in good]),
                    "gradients": gm([r["gradients_total"] for r in good]),
                    "wall_seconds": gm([r["wall_seconds"] for r in good]),
                    "min_bulk": min([r["min_bulk_ess"] for r in good], default=None),
                    "min_tail": min([r["min_tail_ess"] for r in good], default=None),
                    "max_rhat": max([r["max_rhat"] for r in good], default=None),
                    "div": sum(r["divergences"] for r in good),
                    "passed": sum(1 for r in good if r["passed"]),
                    "attached_fraction": med([r.get("attached_fraction") for r in good]),
                    "construct_s": med([r.get("construct_seconds") for r in good]),
                }
    out["aggregates"] = {"|".join(map(str, k)): v for k, v in agg.items()}

    def per_seed_ratio(t, a, ta, b, tb, key="ess_per_second"):
        vals = []
        for s in SEEDS:
            x, y = ok(cells, (t, a, ta, s)), ok(cells, (t, b, tb, s))
            if x and y and y[key] > 0:
                vals.append(x[key] / y[key])
        return gm(vals), vals

    # ---- latency table
    md += ["## (a) Wall per gradient (µs; median over 3 seeds of Rust-side sampling wall / kernel target calls)", "",
           "At threads=4 the value is throughput per gradient across 4 chains. `vs rust` = ratio of medians at the "
           "same thread count; `− rust` = difference at threads=1.", ""]
    lat = {}
    for th in THREADS:
        md += [f"### threads = {th}", "", "| path | " + " | ".join(f"{t} µs | {t} vs rust" for t in TARGETS) + " |",
               "|---|" + "---:|---:|" * len(TARGETS)]
        for a in ARMS:
            row = [a]
            for t in TARGETS:
                v = agg[(t, a, th)]["wall_per_call_us"]
                rr = agg[(t, "rust", th)]["wall_per_call_us"]
                ratio = v / rr if v and rr else None
                lat[f"{t}|{a}|t{th}"] = {"us": v, "vs_rust": ratio,
                                         "minus_rust_us": (v - rr) if (v is not None and rr is not None) else None}
                row += [fmt(v), fmt(ratio)]
            md.append("| " + " | ".join(row) + " |")
        md.append("")
    md += ["### threads = 1, cost above the pure-Rust target (µs per gradient)", "",
           "| path | " + " | ".join(TARGETS) + " |", "|---|" + "---:|" * len(TARGETS)]
    for a in OW + P["nutpie_arms"]:
        md.append("| " + a + " | " + " | ".join(fmt(lat[f"{t}|{a}|t1"]["minus_rust_us"]) for t in TARGETS) + " |")
    md.append("")
    out["latency"] = lat

    # ---- micro
    md += ["## (a) Micro (median µs per call through the Python surface; cfunc and gil_free via ctypes; "
           "rust = native evaluation, Instant-timed)", ""]
    comps = sorted({k for r in micro.values() if r.get("status") == "ok" for k in r["components"]})
    md += ["| target | path | " + " | ".join(comps) + " |", "|---|---|" + "---:|" * len(comps)]
    mic = {}
    for t in TARGETS:
        for pth in P["micro_paths"]:
            r = micro.get((t, pth))
            if not r or r.get("status") != "ok":
                md.append(f"| {t} | {pth} | " + " | ".join("—" for _ in comps) + " |")
                continue
            vals = {k: r["components"].get(k, {}).get("median_us") for k in comps}
            mic[f"{t}|{pth}"] = vals
            md.append(f"| {t} | {pth} | " + " | ".join(fmt(vals[k]) for k in comps) + " |")
    md.append("")
    out["micro"] = mic

    # ---- sampler table
    md += ["## (b) Sampler cells (3 seeds; ESS/s and ESS/grad geomeans; wall pinned, co-tenanted)", ""]
    for t in TARGETS:
        md += [f"### {t}", "",
               "| arm | threads | ok | ESS/s | ESS/grad x1e3 | grads | wall s | µs/grad | min bulk | min tail | "
               "max R-hat | div | gates | attached | construct s |",
               "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|"]
        for a in ARMS:
            for th in THREADS:
                g = agg[(t, a, th)]
                md.append(f"| {a} | {th} | {g['ok']}/{g['n']} | {fmt(g['ess_per_second'])} | "
                          f"{fmt(1e3 * g['ess_per_gradient'] if g['ess_per_gradient'] else None, 3)} | "
                          f"{fmt(g['gradients'])} | {fmt(g['wall_seconds'])} | {fmt(g['wall_per_call_us'])} | "
                          f"{fmt(g['min_bulk'])} | {fmt(g['min_tail'])} | {fmt(g['max_rhat'], 4)} | {g['div']} | "
                          f"{g['passed']}/{g['n']} | {fmt(g['attached_fraction'])} | {fmt(g['construct_s'])} |")
        md.append("")

    # ---- ratios
    ratios = {}
    md += ["## Ratios (geomean over seeds of per-seed ratios)", "",
           "| target | arm | t4/t1 ESS/s | vs nutpie ESS/s t1 (cores 1) | vs nutpie ESS/s t4 (cores 4) | "
           "ESS/grad vs rust (t1) | nutpie ESS/grad ÷ arm ESS/grad |",
           "|---|---|---:|---:|---:|---:|---:|"]
    for t in TARGETS:
        for a in OW + P["nutpie_arms"]:
            t41, _ = per_seed_ratio(t, a, 4, a, 1)
            n1, _ = per_seed_ratio(t, a, 1, "nutpie", 1)
            n4, _ = per_seed_ratio(t, a, 4, "nutpie", 4)
            eg = agg[(t, a, 1)]["ess_per_gradient"]
            egr = agg[(t, "rust", 1)]["ess_per_gradient"]
            egn = agg[(t, "nutpie", 1)]["ess_per_gradient"]
            ratios[f"{t}|{a}"] = {"t4_over_t1": t41, "vs_nutpie_t1": n1, "vs_nutpie_t4": n4,
                                  "ess_per_grad_vs_rust": eg / egr if eg and egr else None,
                                  "nutpie_gap": egn / eg if eg and egn else None}
            md.append(f"| {t} | {a} | {fmt(t41)} | {fmt(n1, 3)} | {fmt(n4, 3)} | "
                      f"{fmt(ratios[f'{t}|{a}']['ess_per_grad_vs_rust'], 3)} | {fmt(ratios[f'{t}|{a}']['nutpie_gap'], 3)} |")
    md.append("")
    out["ratios"] = ratios

    # ---- nutpie gap
    gaps = {t: ratios[f"{t}|pymc"]["nutpie_gap"] for t in TARGETS}
    pooled = gm(list(gaps.values())) if all(gaps.values()) else None
    all_arm_gap = {a: gm([ratios[f"{t}|{a}"]["nutpie_gap"] for t in TARGETS]) for a in OW}
    w58 = P["windows_reference"]["WP58_nutpie_gap_python_path"]
    md += ["## nutpie per-gradient gap (nutpie ESS/grad ÷ oWALNUTS ESS/grad; cores/threads 1 cells)", "",
           "| model | Linux, from_pymc (primary) | Linux, pooled over all oWALNUTS arms | WP58 Windows (Python path) | "
           "WP47 Windows |", "|---|---:|---:|---:|---:|"]
    w47 = P["windows_reference"]["WP47_nutpie_per_gradient_lead"]
    for i, t in enumerate(TARGETS):
        arms_gap = gm([ratios[f"{t}|{a}"]["nutpie_gap"] for a in OW])
        md.append(f"| {t} | {fmt(gaps[t], 3)} | {fmt(arms_gap, 3)} | {w58[t]:.2f} | {w47[i]:.2f} |")
    md.append(f"| pooled (geomean over models) | {fmt(pooled, 3)} | {fmt(gm(list(all_arm_gap.values())), 3)} | "
              f"{w58['pooled']:.2f} | {gm(w47):.2f} |")
    md += ["", "Per-arm pooled gap: " + ", ".join(f"{a} {fmt(v, 3)}" for a, v in all_arm_gap.items()), ""]
    out["nutpie_gap"] = {"per_model_pymc": gaps, "pooled_pymc": pooled, "pooled_per_arm": all_arm_gap}

    # ---- bit identity
    def same(t, a, ta, b, tb, s):
        x, y = ok(cells, (t, a, ta, s)), ok(cells, (t, b, tb, s))
        if not (x and y):
            return None
        return x["samples_sha256"] == y["samples_sha256"]

    bit = {}
    comps_bi = []
    for t in TARGETS:
        for a, b in (("rust", "cfunc"), ("cfunc", "py-njit"), ("rust", "py-njit"), ("pymc", "pymc-gilfree")):
            for th in THREADS:
                comps_bi.append((f"{a}=={b}|{t}|t{th}", [same(t, a, th, b, th, s) for s in SEEDS]))
        for a in ARMS:
            comps_bi.append((f"t1==t4|{a}|{t}", [same(t, a, 1, a, 4, s) for s in SEEDS]))
    md += ["## Bit identity (sha256 of retained draws)", "", "| comparison | identical / compared |", "|---|---|"]
    for name, vals in comps_bi:
        v = [x for x in vals if x is not None]
        bit[name] = [sum(v), len(v)]
        md.append(f"| {name} | {sum(v)}/{len(v)} |")
    md.append("")
    # starts: chosen candidate indices and evaluation counts vs the rust arm
    st_same, st_n = 0, 0
    for (t, a, th, s), r in cells.items():
        if a in ("rust", "nutpie") or r.get("status") != "ok":
            continue
        rr = ok(cells, (t, "rust", th, s))
        if rr:
            st_n += 1
            st_same += int(r["start_evaluations"] == rr["start_evaluations"])
    bit["start_evaluations_equal_rust"] = [st_same, st_n]
    md += [f"Best-of-16 start evaluation counts equal to the Rust arm's: {st_same}/{st_n} Python cells.", ""]
    out["bit_identity"] = bit

    # ---- predictions
    pr = {}
    p1 = PRED["P1"]["ranges_t1_us"]
    hits = {f"{a}|{t}": all(inr(v, p1[a][t]) for v in agg[(t, a, 1)]["wall_per_call_us_seeds"] if v is not None)
            and agg[(t, a, 1)]["ok"] > 0 for a in p1 for t in TARGETS}
    pr["P1"] = {"held": sum(hits.values()), "of": len(hits), "cells": hits}
    p2 = PRED["P2"]["ratio_ranges"]
    c2 = {}
    for t in TARGETS:
        c2[f"cfunc_t1|{t}"] = inr(lat[f"{t}|cfunc|t1"]["vs_rust"], p2["cfunc_t1"])
        c2[f"cfunc_t4|{t}"] = inr(lat[f"{t}|cfunc|t4"]["vs_rust"], p2["cfunc_t4"])
        c2[f"pymc-gilfree_t1|{t}"] = inr(lat[f"{t}|pymc-gilfree|t1"]["vs_rust"], p2["pymc-gilfree_t1"][t])
        a, b = lat[f"{t}|py-njit|t1"]["us"], lat[f"{t}|cfunc|t1"]["us"]
        c2[f"py-njit_minus_cfunc_t1|{t}"] = inr(a - b if a is not None and b is not None else None,
                                               p2["py-njit_minus_cfunc_t1_us"])
    pr["P2"] = {"held": sum(c2.values()), "of": len(c2), "cells": c2}
    p3 = PRED["P3"]["ranges"]
    c3 = {f"{a}|{t}": inr(ratios[f"{t}|{a}"]["t4_over_t1"], p3[a]) for a in p3 for t in TARGETS}
    pr["P3"] = {"held": sum(c3.values()), "of": len(c3), "cells": c3}
    c4 = {}
    for name, (n_same, n) in bit.items():
        if name.startswith(("rust==", "cfunc==", "t1==t4")):
            c4[name] = n_same == n and n > 0
        elif name.startswith("pymc==pymc-gilfree") and ("|eight|" in name or "|hier|" in name):
            c4[name] = n_same == 0 and n > 0
        elif name == "start_evaluations_equal_rust":
            c4[name] = n_same == n and n > 0
    pr["P4"] = {"held": sum(c4.values()), "of": len(c4), "cells": c4}
    c5 = {f"{a}|{t}": inr(ratios[f"{t}|{a}"]["ess_per_grad_vs_rust"], PRED["P5"]["range"])
          for a in OW if a != "rust" for t in TARGETS}
    pr["P5"] = {"held": sum(c5.values()), "of": len(c5), "cells": c5}
    c6 = {f"gap|{t}": inr(gaps[t], PRED["P6"]["per_model_gap"]) for t in TARGETS}
    c6["pooled"] = inr(pooled, PRED["P6"]["pooled_gap"])
    pr["P6"] = {"held": sum(c6.values()), "of": len(c6), "cells": c6}
    c7 = {}
    for key, rng in PRED["P7"]["ranges"].items():
        a, th = key.rsplit("_t", 1)
        for t in TARGETS:
            c7[f"{key}|{t}"] = inr(ratios[f"{t}|{a}"]["vs_nutpie_t" + th], rng)
    pr["P7"] = {"held": sum(c7.values()), "of": len(c7), "cells": c7}
    c8 = {"all_cells_ok": out["cells_ok"] == len(SEEDS) * len(TARGETS) * len(ARMS) * len(THREADS)
          and out["micro_ok"] == len(TARGETS) * len(P["micro_paths"])}
    for a in OW:
        c8[f"gates_t1_ge8|{a}"] = sum(agg[(t, a, 1)]["passed"] for t in TARGETS) >= 8
    c8["nutpie_eight_fails_ge2"] = (agg[("eight", "nutpie", 1)]["ok"] - agg[("eight", "nutpie", 1)]["passed"]) >= 2
    c8["nutpie_gauss_3of3"] = agg[("gauss100", "nutpie", 1)]["passed"] == 3
    c8["nutpie_hier_ge2"] = agg[("hier", "nutpie", 1)]["passed"] >= 2
    pr["P8"] = {"held": sum(c8.values()), "of": len(c8), "cells": c8}
    out["predictions"] = pr
    md += ["## Predictions", "", "| id | held / of | misses |", "|---|---|---|"]
    for k, v in pr.items():
        misses = [n for n, h in v["cells"].items() if not h]
        md.append(f"| {k} | {v['held']}/{v['of']} | {', '.join(misses) if misses else '—'} |")
    md.append("")

    # ---- decision rule
    dr = {}
    r1_ratio = {t: per_seed_ratio(t, "pymc-gilfree", 4, "pymc", 1)[0] for t in TARGETS}
    r1 = (all(v is not None and v >= 2.0 for v in r1_ratio.values())
          and all(agg[(t, "pymc-gilfree", th)]["ok"] == len(SEEDS) for t in TARGETS for th in THREADS)
          and all(agg[(t, "pymc-gilfree", 4)]["passed"] >= agg[(t, "pymc", 1)]["passed"] for t in TARGETS))
    dr["R1"] = {"gilfree_t4_over_pymc_t1": r1_ratio, "recommend_gil_free_first": r1}
    r1_arm, r1_th = ("pymc-gilfree", 4) if r1 else ("pymc", 1)
    r2 = {}
    for t in TARGETS:
        ratio, _ = per_seed_ratio(t, "nutpie", 4, r1_arm, r1_th)
        npass = agg[(t, "nutpie", 4)]["passed"]
        nfail = agg[(t, "nutpie", 4)]["ok"] - npass + (len(SEEDS) - agg[(t, "nutpie", 4)]["ok"])
        if nfail >= 2:
            verdict = "nutpie fails the gates (state the failure, not the speed)"
        elif ratio is not None and ratio >= 1.25 and npass >= 2:
            verdict = f"nutpie faster by {ratio:.2f}x"
        else:
            verdict = f"oWALNUTS {r1_arm} t{r1_th} competitive (nutpie/oWALNUTS {fmt(ratio)})"
        r2[t] = {"nutpie_c4_over_r1_path": ratio, "nutpie_c4_passed": npass, "verdict": verdict}
    dr["R2"] = r2
    r3_ratio = {t: per_seed_ratio(t, "cfunc", 4, "py-njit", 1)[0] for t in TARGETS}
    r3_lat = {t: lat[f"{t}|cfunc|t4"]["vs_rust"] for t in TARGETS}
    dr["R3"] = {"cfunc_t4_over_pynjit_t1": r3_ratio,
                "recommend_cfunc": all(v is not None and v >= 2.0 for v in r3_ratio.values()),
                "cfunc_t4_wall_vs_rust": r3_lat,
                "within_1.5x_of_rust": all(v is not None and v <= 1.5 for v in r3_lat.values())}
    r4 = {}
    for a in ("py-njit", "jax", "pymc"):
        v = {t: ratios[f"{t}|{a}"]["t4_over_t1"] for t in TARGETS}
        if sum(1 for x in v.values() if x is not None and x < 1.0) >= 2:
            verdict = "use threads=1"
        elif all(x is not None and x >= 1.2 for x in v.values()):
            verdict = "threads=4 helps"
        else:
            verdict = "threads makes little difference"
        r4[a] = {"t4_over_t1": v, "verdict": verdict}
    dr["R4"] = r4
    if pooled is not None and 1.4 <= pooled <= 2.1 and all(g is not None and g > 1.2 for g in gaps.values()):
        r5 = "persists on Linux"
    elif pooled is not None and pooled < 1.25:
        r5 = "did not reproduce on Linux"
    else:
        r5 = "smaller on Linux" if pooled is not None and pooled < 1.4 else "reported with the Linux numbers (outside [1.4, 2.1])"
    dr["R5"] = {"pooled": pooled, "per_model": gaps, "verdict": r5}
    r6_ratio = {t: per_seed_ratio(t, "jax", 1, "py-njit", 1)[0] for t in TARGETS}
    dr["R6"] = {"jax_t1_over_pynjit_t1": r6_ratio,
                "competitive": all(v is not None and v >= 0.5 for v in r6_ratio.values())}
    out["decision"] = dr
    md += ["## Decision rule (frozen)", "", "```json", json.dumps(dr, indent=1, default=float), "```", ""]

    (ART / "summary.json").write_text(json.dumps(out, indent=1, default=float), encoding="utf-8")
    (ART / "results-table.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
