#!/usr/bin/env python3
"""WP89 mechanism tables from the per-transition telemetry (run after `run_study.py analyze`).

    python mechanism.py            # reads artifacts/summary.json and artifacts/telemetry/*.json.gz
                                   # writes artifacts/mechanism.json and artifacts/mechanism.md

For every oWALNUTS cell of Part A (and the Part B arms with telemetry) it classifies each chain as
trapped (the frozen census, from summary.json), near-trap (step below NEAR_STEP at the end of S1
but not trapped: a chain that escaped) or healthy, and summarises per class: the start (log_sigma,
log density), the step at the checkpoints, the first transition at which the step fell below
1e-4, the log density and log_sigma at the end of S1 and of warmup, the max |gradient| over
S1, the first installed metric (mass at transition 99: median, min, max over coordinates and the
share of coordinates at the regularisation floor), and the escape transition of near-traps
(first transition at which log_sigma < 0). CmdStan cells contribute their step traces and
log_sigma traces; nutpie its step traces.
"""
from __future__ import annotations

import gzip
import json
import os
import statistics
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ART = Path(os.environ.get("WP89_ART", HERE / "artifacts"))
CELLS, TELEM = ART / "cells", ART / "telemetry"
NEAR_STEP = 1e-5
CHECK = [5, 10, 25, 74, 99, 149, 249, 449, 949, 999]
FLOOR_MASS = 1.0 / (1e-3 * 5.0 / 30.0)  # Stan floor at n = 25: variance 1.667e-4, mass 6000


def q(xs, digits=4):
    xs = [float(x) for x in xs if x is not None and np.isfinite(x)]
    if not xs:
        return None
    v = np.quantile(xs, [0, 0.25, 0.5, 0.75, 1])
    return {"n": len(xs), "min": round(v[0], digits), "q25": round(v[1], digits), "median": round(v[2], digits),
            "q75": round(v[3], digits), "max": round(v[4], digits)}


def chain_record(cell, tel, c, cls):
    F = {k: i for i, k in enumerate(tel["fields"])}
    R = np.asarray([[np.nan if v is None else v for v in r] for r in tel["rows"][c]], dtype=float)
    R = R[R[:, F["epoch"]] == R[:, F["epoch"]].max()] if "epoch" in F else R  # the final epoch (restarted chains)
    step, lp, ls, grad, moved, stop = (R[:, F[k]] for k in ("step", "log_density", "log_sigma", "max_abs_gradient", "position_changed", "stop"))
    t = R[:, F["t"]].astype(int)
    at = lambda arr, i: float(arr[i]) if i < len(arr) else None
    below = np.nonzero(step < 1e-4)[0]
    escape = np.nonzero(ls < 0)[0]
    m99 = [m for m in tel["installed_metrics"] if m["chain"] == c and m["transition"] == 99 and m.get("epoch", 0) == int(R[0, F["epoch"]])]
    metric = None
    if m99:
        d = np.asarray(m99[0]["diagonal"])
        metric = {"median": float(np.median(d)), "min": float(d.min()), "max": float(d.max()),
                  "share_at_floor": float(np.mean(np.abs(d - FLOOR_MASS) / FLOOR_MASS < 0.05)), "step_after": m99[0]["step_after"]}
    s1 = slice(75, 100)
    return {"seed": cell["seed"], "chain": c, "class": cls,
            "start_log_sigma": cell["start_log_sigma"][c], "start_log_density": cell["init"]["start_log_densities"][c],
            "step_at": {str(i): at(step, i) for i in CHECK},
            "first_t_step_below_1e-4": int(t[below[0]]) if len(below) else None,
            "lp_after_t0": at(lp, 0), "log_sigma_after_t0": at(ls, 0),
            "lp_S1_median": float(np.nanmedian(lp[s1])), "log_sigma_S1_median": float(np.nanmedian(ls[s1])),
            "max_abs_gradient_S1_median": float(np.nanmedian(grad[s1])), "moved_S1": float(np.nanmean(moved[s1])),
            "lp_end_warmup": float(np.nanmedian(lp[950:1000])), "log_sigma_end_warmup": float(np.nanmedian(ls[950:1000])),
            "lp_retained_median": float(np.nanmedian(lp[1000:])), "metric_t99": metric,
            "escape_t": int(t[escape[0]]) if len(escape) else None,
            "warmup_gradients": float(np.nansum(R[:1000, F["target_evaluations"]])),
            "final_step": at(step, len(step) - 1)}


def main() -> None:
    summary = json.loads((ART / "summary.json").read_text(encoding="utf-8"))
    out = {"near_step": NEAR_STEP, "arms": {}, "chains": []}
    md = ["# WP89 mechanism tables (generated by mechanism.py)", ""]
    for cid, info in summary["cells"].items():
        block, arm, seed = cid.split("-", 1)[0], cid.split("-", 1)[1].rsplit("-", 1)[0], cid.rsplit("-", 1)[1]
        if arm in ("cmdstan", "nutpie"):
            continue
        cp = CELLS / f"{cid}.json"
        tp = TELEM / f"{cid}.json.gz"
        if not cp.exists() or not tp.exists():
            continue
        cell = json.loads(cp.read_text(encoding="utf-8"))
        if cell.get("status") != "ok":
            continue
        tel = json.loads(gzip.open(tp).read())
        trapped = set(info["trapped"])
        for c in range(len(cell["chains_data"])):
            s99 = cell["chains_data"][c]["step_at_transition"].get("99")
            cls = "trapped" if c in trapped else ("near" if (s99 is not None and s99 < NEAR_STEP) else "healthy")
            if cls == "healthy" and arm not in ("defaults",):
                continue  # keep the files small: healthy chains only for A-defaults
            if cls == "healthy" and (int(seed) - 8901001) % 10 != 0:
                continue  # every 10th seed's healthy chains as the comparison class
            try:
                rec = chain_record(cell, tel, c, cls)
            except Exception as e:  # noqa: BLE001
                rec = {"seed": cell["seed"], "chain": c, "class": cls, "error": repr(e)}
            rec["arm"] = f"{block}-{arm}"
            out["chains"].append(rec)
    for arm in sorted({r["arm"] for r in out["chains"]}):
        A = out["arms"][arm] = {}
        for cls in ("trapped", "near", "healthy"):
            rs = [r for r in out["chains"] if r["arm"] == arm and r["class"] == cls and "error" not in r]
            if not rs:
                continue
            A[cls] = {"n": len(rs),
                      "start_log_sigma": q([r["start_log_sigma"] for r in rs], 2),
                      "start_log_density": q([r["start_log_density"] for r in rs], 0),
                      "share_start_log_sigma_above_0.5": float(np.mean([r["start_log_sigma"] > 0.5 for r in rs])),
                      "log_sigma_after_t0": q([r["log_sigma_after_t0"] for r in rs], 2),
                      "step": {str(i): q([r["step_at"][str(i)] for r in rs], 7) for i in CHECK},
                      "first_t_step_below_1e-4": q([r["first_t_step_below_1e-4"] for r in rs], 0),
                      "share_collapsed_by_74": float(np.mean([(r["first_t_step_below_1e-4"] or 10**9) <= 74 for r in rs])),
                      "lp_S1_median": q([r["lp_S1_median"] for r in rs], 0),
                      "log_sigma_S1_median": q([r["log_sigma_S1_median"] for r in rs], 2),
                      "max_abs_gradient_S1_median": q([r["max_abs_gradient_S1_median"] for r in rs], 0),
                      "moved_S1": q([r["moved_S1"] for r in rs], 2),
                      "metric_t99_mass_median": q([r["metric_t99"]["median"] for r in rs if r["metric_t99"]], 1),
                      "metric_t99_share_at_floor": q([r["metric_t99"]["share_at_floor"] for r in rs if r["metric_t99"]], 2),
                      "lp_end_warmup": q([r["lp_end_warmup"] for r in rs], 0),
                      "log_sigma_end_warmup": q([r["log_sigma_end_warmup"] for r in rs], 2),
                      "lp_retained_median": q([r["lp_retained_median"] for r in rs], 0),
                      "escape_t": q([r["escape_t"] for r in rs], 0),
                      "warmup_gradients": q([r["warmup_gradients"] for r in rs], 0),
                      "final_step": q([r["final_step"] for r in rs], 6)}
        md.append(f"## {arm}\n")
        md.append("| class | n | start log_sigma (med) | start lp (med) | share start ls > 0.5 | ls after t0 (med) | step t=10 (med) | step t=99 (med) | first t step<1e-4 (med) | lp S1 (med) | ls S1 (med) | max grad S1 (med) | moved S1 | mass t99 (med) | share at floor (med) | lp end warmup (med) | ls end warmup (med) | escape t (med) | warmup gradients (med) |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for cls, d in A.items():
            g = lambda k, sub="median": (d[k] or {}).get(sub) if isinstance(d[k], dict) else d[k]
            md.append(f"| {cls} | {d['n']} | {g('start_log_sigma')} | {g('start_log_density')} | {d['share_start_log_sigma_above_0.5']:.2f} | {g('log_sigma_after_t0')} | "
                      f"{(d['step']['10'] or {}).get('median')} | {(d['step']['99'] or {}).get('median')} | {g('first_t_step_below_1e-4')} | {g('lp_S1_median')} | {g('log_sigma_S1_median')} | "
                      f"{g('max_abs_gradient_S1_median')} | {g('moved_S1')} | {g('metric_t99_mass_median')} | {g('metric_t99_share_at_floor')} | {g('lp_end_warmup')} | {g('log_sigma_end_warmup')} | {g('escape_t')} | {g('warmup_gradients')} |")
        md.append("")
    # CmdStan and nutpie step traces at the checkpoints, trapped vs healthy
    for arm in ("A-cmdstan", "A-nutpie"):
        rows = {"trapped": [], "healthy": []}
        for cid, info in summary["cells"].items():
            if not cid.startswith(arm):
                continue
            cell = json.loads((CELLS / f"{cid}.json").read_text(encoding="utf-8"))
            if cell.get("status") != "ok":
                continue
            for c, s in enumerate(cell["step_at_checkpoints"]):
                rec = {"seed": cell["seed"], "chain": c, "steps": s,
                       "start_log_sigma": (cell.get("start_log_sigma") or cell.get("first_draw_log_sigma"))[c],
                       "start_lp": ((cell.get("init") or {}).get("start_log_densities") or cell.get("first_draw_log_density"))[c],
                       "ls_trace": cell["warmup_log_sigma_trace_every_10"][c][:12], "lp_trace": cell["warmup_lp_trace_every_10"][c][:12]}
                rows["trapped" if c in info["trapped"] else "healthy"].append(rec)
        out["arms"][arm] = {cls: {"n": len(rs), "start_log_sigma": q([r["start_log_sigma"] for r in rs], 2),
                                  "start_lp": q([r["start_lp"] for r in rs], 0),
                                  "steps": {k: q([r["steps"][k] for r in rs], 7) for k in rows["healthy"][0]["steps"]} if rows["healthy"] else None,
                                  "trapped_examples": rs[:6] if cls == "trapped" else None}
                            for cls, rs in rows.items() if rs}
        md.append(f"## {arm}\n")
        for cls, d in out["arms"][arm].items():
            md.append(f"- {cls}: n {d['n']}, start log_sigma median {d['start_log_sigma']['median']}, steps at checkpoints (median): " +
                      ", ".join(f"{k} {v['median']:.2g}" for k, v in d["steps"].items()))
        md.append("")
    md.append("## Every trapped and near-trapped oWALNUTS chain\n")
    md.append("| arm | seed | chain | class | start ls | start lp | ls after t0 | step t=10 | step t=99 | first t step<1e-4 | lp S1 | max grad S1 | mass t99 | floor share | escape t | ls end warmup | lp retained |")
    md.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in out["chains"]:
        if r["class"] == "healthy" or "error" in r:
            continue
        m = r["metric_t99"] or {}
        md.append(f"| {r['arm']} | {r['seed']} | {r['chain']} | {r['class']} | {r['start_log_sigma']:.2f} | {r['start_log_density']:.0f} | {r['log_sigma_after_t0']:.2f} | "
                  f"{r['step_at']['10']:.1e} | {r['step_at']['99']:.1e} | {r['first_t_step_below_1e-4']} | {r['lp_S1_median']:.0f} | {r['max_abs_gradient_S1_median']:.1e} | "
                  f"{m.get('median', float('nan')):.0f} | {m.get('share_at_floor', float('nan')):.2f} | {r['escape_t']} | {r['log_sigma_end_warmup']:.2f} | {r['lp_retained_median']:.0f} |")
    (ART / "mechanism.json").write_text(json.dumps(out, indent=1, default=float) + "\n", encoding="utf-8")
    (ART / "mechanism.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("mechanism written:", {arm: {cls: d["n"] for cls, d in a.items()} for arm, a in out["arms"].items()})


if __name__ == "__main__":
    sys.exit(main())
